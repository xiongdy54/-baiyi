const d91 = require("./d91.bundle.cjs");
const fs = require("fs");
const path = require("path");

let pass = 0;
let fail = 0;
function check(name, cond, expected, actual) {
  if (cond) { pass++; console.log(`  ✓ ${name}`); }
  else { fail++; console.log(`  ✗ ${name}\n      期望: ${JSON.stringify(expected)}\n      实际: ${JSON.stringify(actual)}`); }
}

// ---------- P1 pack lint（§8.3：法务红线的机械化） ----------
console.log("== P1 pack lint（必填字段 + ASD-STE100 只出现在 derivedFrom + original-wording） ==");
const PROFILE_DIR = path.join(__dirname, "..", "electron", "ste-profiles");
const PACK_FILES = ["zh-Hans.json", "en.json", "universal.json"];
check("三个 pack 文件在场", PACK_FILES.every((f) => fs.existsSync(path.join(PROFILE_DIR, f))), PACK_FILES.join(" "), fs.readdirSync(PROFILE_DIR).join(" "));
for (const f of PACK_FILES) {
  const raw = fs.readFileSync(path.join(PROFILE_DIR, f), "utf8");
  const pack = JSON.parse(raw);
  const required = ["lang", "name", "derivedFrom", "licenseNote", "sentence", "voice", "lexicon"];
  const missing = required.filter((k) => pack[k] === undefined || pack[k] === null);
  check(`${f} 必填字段齐全（lang/name/derivedFrom/licenseNote/sentence/voice/lexicon）`, missing.length === 0, "无缺失", missing.join(",") || "—");
  // "ASD-STE100" 仅允许出现在 derivedFrom 字段（规则正文/说明里不得出现——§2.2 红线）
  const outside = JSON.stringify({ ...pack, derivedFrom: undefined }).includes("ASD-STE100");
  check(`${f} 规则正文不含 ASD-STE100（仅 derivedFrom 可引用名称）`, !outside, false, outside);
  check(`${f} licenseNote 含 original-wording 声明`, String(pack.licenseNote).includes("original-wording"), "含 original-wording", pack.licenseNote);
  const derived = JSON.stringify(pack.derivedFrom);
  check(`${f} derivedFrom 有结构参照来源声明`, derived.includes("ISO 24495-1") || derived.includes("ASD-STE100"), "ISO/STE 引用", derived.slice(0, 80));
  check(`${f} lexicon 非空且全部为字符串`, Array.isArray(pack.lexicon) && pack.lexicon.length > 0 && pack.lexicon.every((x) => typeof x === "string"), true, typeof pack.lexicon);
}
// 渲染层注册表与盘上 pack 一致（Vite 静态导入 ≠ fs 直读的两条路径不漂移）
for (const key of Object.keys(d91.STE_PROFILES)) {
  const reg = d91.STE_PROFILES[key];
  const disk = JSON.parse(fs.readFileSync(path.join(PROFILE_DIR, `${key}.json`), "utf8"));
  check(`注册表[${key}] 与盘上 pack 一致`, JSON.stringify(reg) === JSON.stringify(disk), key, key);
}

// ---------- P2 回退链（§8.4） ----------
console.log("== P2 回退链：精确 → 基础语言 → en → universal ==");
check("resolve('zh-Hant-TW') → zh-Hans", d91.resolveProfile("zh-Hant-TW").lang === "zh-Hans", "zh-Hans", d91.resolveProfile("zh-Hant-TW").lang);
check("resolve('zh') → zh-Hans", d91.resolveProfile("zh").lang === "zh-Hans", "zh-Hans", d91.resolveProfile("zh").lang);
check("resolve('en') → en", d91.resolveProfile("en").lang === "en", "en", d91.resolveProfile("en").lang);
check("resolve('en-US') → en（大小写归一）", d91.resolveProfile("en-US").lang === "en", "en", d91.resolveProfile("en-US").lang);
check("resolve('fr') → en（未知语言落 en）", d91.resolveProfile("fr").lang === "en", "en", d91.resolveProfile("fr").lang);
check("resolve('') → universal（缺省兜底）", d91.resolveProfile("").lang === "universal", "universal", d91.resolveProfile("").lang);
check("resolve(undefined) → universal", d91.resolveProfile(undefined).lang === "universal", "universal", d91.resolveProfile(undefined).lang);
check("resolve('zh-Hans') 输出语言常量 = zh-Hans（P0 恒中文）", d91.STE_OUTPUT_LANG === "zh-Hans", "zh-Hans", d91.STE_OUTPUT_LANG);
const formatted = d91.formatProfile(d91.resolveProfile("en"));
check("formatProfile 产出注入块（含 pack 名与规则行）", formatted.includes("Plain English Profile") && formatted.split("\n").length > 3, ">3 行", formatted.split("\n").length);

// ---------- P3 本地路由器金样例（§8.9） ----------
console.log("== P3 routeExplainMode 金样例（结构平直长句不触发；嵌套/否定/被动为主因子） ==");
const enPassiveNested =
  "The configuration parameters that were generated by the tool which was installed by the administrator are not used by the runtime module unless they have been overridden and cannot be ignored by the loader.";
check("英文长被动嵌套句 → ste", d91.routeExplainMode(enPassiveNested) === "ste", "ste", d91.routeExplainMode(enPassiveNested));
check("中文短定义句 → general", d91.routeExplainMode("中位数是把一组数据排序后位于中间位置的数，它对极端值不敏感。") === "general", "general", d91.routeExplainMode("中位数是把一组数据排序后位于中间位置的数，它对极端值不敏感。"));
check("英文短定义句 → general", d91.routeExplainMode("A median is the middle value of a sorted list of numbers.") === "general", "general", d91.routeExplainMode("A median is the middle value of a sorted list of numbers."));
const zhFlatLong = "他昨天早上七点钟从家里出门走到地铁站坐了三站地铁到了公司楼下买了一杯豆浆和一个包子进电梯上到十八层打卡开机泡茶然后打开电脑开始回复邮件一直工作到中午十二点才起身去楼下吃午饭。";
check("中文结构平直长句 → general（句长只作低权重因子）", d91.routeExplainMode(zhFlatLong) === "general", "general", d91.routeExplainMode(zhFlatLong));
check("否定叠加句 → ste", d91.routeExplainMode("这种做法并非没有根据，但也不是没有任何风险，你不能说它完全没有问题，只是目前还没有足够的证据而已。") === "ste", "ste", d91.routeExplainMode("这种做法并非没有根据，但也不是没有任何风险，你不能说它完全没有问题，只是目前还没有足够的证据而已。"));
check("极短文本 → general（不足 MIN_CHARS 不路由）", d91.routeExplainMode("被否定了") === "general", "general", d91.routeExplainMode("被否定了"));
check("空串 → general", d91.routeExplainMode("") === "general", "general", d91.routeExplainMode(""));
const zhBracketNest = "系统配置（包括运行参数（如超时阈值、重试次数等）与安全设置）需要在部署前逐项核对。";
check("中文括号嵌套句 → ste", d91.routeExplainMode(zhBracketNest) === "ste", "ste", d91.routeExplainMode(zhBracketNest));
check("权重/阈值常量已导出（金样例校准的载体）", typeof d91.EXPLAIN_ROUTER_THRESHOLD === "number" && typeof d91.EXPLAIN_ROUTER_WEIGHTS === "object", true, typeof d91.EXPLAIN_ROUTER_WEIGHTS);

// ---------- P4 机器标记契约（§8.5 前置：渲染端可解析） ----------
console.log("== P4 ste 机器标记解析 ==");
const sample = "<!--ste:matLang=en-->\n<!--ste:points=3-->\n<!--ste:readings=2-->\n\n# 歧义点\n...";
const m1 = d91.parseSteMarkers(sample);
check("解析 matLang/points/readings", m1.matLang === "en" && m1.points === 3 && m1.readings === 2, { matLang: "en", points: 3, readings: 2 }, m1);
const m2 = d91.parseSteMarkers("<!--ste:matLang=unknown-->\n<!--ste:points=0-->\n\n# 简明改写");
check("points=0 无 readings（省略合法）", m2.points === 0 && m2.readings === undefined, { points: 0, readings: undefined }, m2);
check("无标记 → 空对象（通用解读结果不含标记）", Object.keys(d91.parseSteMarkers("普通回答")).length === 0, "{}", d91.parseSteMarkers("普通回答"));
check("stripSteMarkers 剥离注释", d91.stripSteMarkers("<!--ste:points=1-->正文").trim() === "正文", "正文", d91.stripSteMarkers("<!--ste:points=1-->正文"));
const cats = d91.STE_CATEGORIES.map((c) => c.key);
check("歧义类别封闭集 = 10 类且 key 唯一", cats.length === 10 && new Set(cats).size === 10, 10, cats.length);

// ---------- P5 事后建议相似性（§8.10 前置） ----------
console.log("== P5 isLikelySameText（改写≈原文判定） ==");
const src = "系统在特定条件下可能会出现一定程度的性能波动，需要用户自行判断当前状态是否满足运行要求。";
check("改写≈原文（近乎照抄）→ true", d91.isLikelySameText(src, `<!--ste:points=0-->\n\n## 简明改写\n\n${src}`) === true, true, d91.isLikelySameText(src, src));
check("改写实质不同 → false", d91.isLikelySameText(src, "并发用户超过两百时，系统响应会变慢约两秒。请先确认负载再评估体验。") === false, false, d91.isLikelySameText(src, "并发用户超过两百时，系统响应会变慢约两秒。请先确认负载再评估体验。"));
check("源文本过短 → false（incidental 命中防护）", d91.isLikelySameText("系统很慢", "系统很慢") === false, false, d91.isLikelySameText("系统很慢", "系统很慢"));

console.log(`\n${fail === 0 ? "ALL PASS" : "FAILED"}: ${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
